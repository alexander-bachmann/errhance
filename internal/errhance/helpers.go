func printNode(src string, node ast.Node) {
	fmt.Printf("%T: %s\n", node, src[int(node.Pos())-1:int(node.End()-1)])
}

// castSnippet makes it easier to test functions that interact with ast.Node types
// Usage: ifStmt, err := castSnippet[*ast.IfStmt]("if err != nil { return }")
func castSnippet[T ast.Node](snippet string) (T, error) {
	var t T
	src := fmt.Sprintf(`package main
func main() {
	%s
}`, snippet)
	f, err := parser.ParseFile(token.NewFileSet(), "", src, 0)
	if err != nil {
		return t, fmt.Errorf("parser.ParseFile: %w", err)
	}
	ast.Inspect(f, func(n ast.Node) bool {
		if node, ok := n.(T); ok {
			t = node
			return false
		}
		return true
	})
	v := reflect.ValueOf(t)
	if (v.Kind() == reflect.Ptr || v.Kind() == reflect.Interface) && v.IsNil() {
		return t, fmt.Errorf("%T not found", t)
	}
	return t, nil
}

func containsOmitComment(src string) bool {
	omitComments := []string{
		"noeh", "no eh",
		"noerrhance", "no errhance",
	}
	for _, comment := range omitComments {
		if strings.Contains(src, "//") && strings.Contains(src, comment) {
			return true
		}
	}
	return false
}

func isGeneratedFile(src string) bool {
	snippets := []string{
		"code generated",
		"generated code",
		"do not edit",
		"autogenerated",
		"auto-generated",
		"generated by",
		"do not modify",
		"this file was generated",
	}
	lines := strings.Split(src, "\n")
	for _, line := range lines {
		if strings.HasPrefix(line, "package") {
			return false
		}
		for _, snippet := range snippets {
			if strings.Contains(strings.ToLower(line), snippet) {
				return true
			}
		}
	}
	return false
}

func runGoImportsOnFile(path string) error {
	cmd := exec.Command("goimports", "-w", path)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("cmd.CombinedOutput: %w: %s", err, output)
	}
	return nil
}

func inGoProject() (bool, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return false, fmt.Errorf("os.Getwd: %w", err)
	}
	for {
		goModPath := filepath.Join(cwd, "go.mod")
		if _, err := os.Stat(goModPath); err != nil {
			if os.IsNotExist(err) {
				// go.mod not found, check the parent directory.
			} else {
				return false, fmt.Errorf("os.Stat: %s: %w", goModPath, err)
			}
		} else {
			return true, nil
		}
		parent := filepath.Dir(cwd)
		if parent == cwd { // reached the root
			break
		}
		cwd = parent
	}
	return false, nil
}

func downloadGoimportsIfMissing() error {
	if _, err := exec.LookPath("goimports"); err == nil {
		return nil
	}
	cmd := exec.Command("go", "install", "golang.org/x/tools/cmd/goimports@latest")
	output, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("cmd.CombinedOutput: %w: %s", err, output)
	}
	return nil
}
