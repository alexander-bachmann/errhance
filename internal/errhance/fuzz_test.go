package errhance

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
	"testing"
)

const fuzzSourceBase = `package p
type failure struct{}
func (failure) Error() string { return "failure" }
func produce() error { return failure{} }
`

func FuzzSource(f *testing.F) {
	for _, src := range []string{
		"", "package p\n", "package p\nfunc broken(", "package p\nvar x int = false",
		fuzzSourceBase + `func run() error { e := produce(); if e != nil { return e }; return nil }`,
		fuzzSourceBase + `func run() func() error { return func() error { e := produce(); if e == nil { return nil }; return e } }`,
		"// Code generated by fixture. DO NOT EDIT.\n" + fuzzSourceBase,
	} {
		f.Add([]byte(src))
	}
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) > 8<<10 {
			t.Skip()
		}
		fuzzCheckSource(t, string(data), NewSourceConfig(), false)
	})
}

func FuzzSourceStructured(f *testing.F) {
	for i := byte(0); i < 10; i++ {
		f.Add("quoted \"%s\"\n", "operation", i, false)
		f.Add("quoted \"%s\"\n", "operation", i, true)
	}
	f.Fuzz(func(t *testing.T, message, identifier string, choice byte, overwrite bool) {
		if len(message) > 128 || len(identifier) > 32 {
			t.Skip()
		}
		// Prefix and map bytes so every fuzz string produces a safe, unique name.
		name := "op"
		for i := range identifier {
			name += string(rune('a' + identifier[i]%26))
		}
		base := fuzzSourceBase + fmt.Sprintf(`
func %s[T any]() error { return produce() }
type receiver struct{}
func makeReceiver(string) receiver { return receiver{} }
func (receiver) Run() error { return produce() }
var errhancefmt int
`, name)
		call := name + "[int]()"
		if choice%2 == 0 {
			call = "makeReceiver(" + strconv.Quote(message) + ").Run()"
		}
		bodies := []string{
			`e := CALL; if e != nil { return e }; return nil`,
			`e := CALL; if nil == e { return nil }; return e`,
			`var e error; if b { e = CALL } else { e = CALL }; if e != nil { return e }; return nil`,
			`e := CALL; if b { e = produce() }; if e != nil { return e }; return nil`,
			`g := func() error { e := CALL; if e != nil { return e }; return nil }; return g()`,
			`e := CALL; func() { e = nil }(); if e != nil { return e }; return nil`,
			`e := CALL; for b { e = produce(); break }; if e != nil { return e }; return nil`,
			`e := CALL; switch b { case true: e = produce() }; if e != nil { return e }; return nil`,
			`e, other := CALL, produce(); e, other = other, e; if e != nil { return e }; if other != nil { return other }; return nil`,
			`e := CALL; if e != nil { return fmt.Errorf("original: %w", e) }; return nil`,
		}
		body := bodies[int(choice)%len(bodies)]
		if int(choice)%len(bodies) == 9 {
			base = strings.Replace(base, "package p\n", "package p\nimport \"fmt\"\n", 1)
		}
		src := base + "func run(b bool) error { " + strings.ReplaceAll(body, "CALL", call) + " }"
		report := fuzzCheckSource(t, src, NewSourceConfig(WithOverwrite(overwrite)), true)
		// A transformer that skips everything satisfies idempotence but is useless.
		// These fixture shapes have deliberately unambiguous, supported origins.
		want := -1
		switch int(choice) % len(bodies) {
		case 0, 1, 2, 4:
			want = 1
		case 8:
			want = 2
		case 9:
			want = 0
			if overwrite {
				want = 1
			}
		}
		if want >= 0 && report.TotalErrorsEnhanced != want {
			t.Fatalf("supported fixture: enhanced %d errors, want %d\n%s", report.TotalErrorsEnhanced, want, src)
		}
	})
}

func fuzzCheckSource(t *testing.T, src string, cfg SourceConfig, valid bool) SourceReport {
	t.Helper()
	report, err := Source(cfg, src)
	if report.Before != src {
		t.Fatal("Source changed Before")
	}
	if err != nil {
		if report.After != src || report.TotalErrorsEnhanced != 0 {
			t.Fatalf("error changed report: %v", err)
		}
		if !errors.Is(err, ErrNoChanges) {
			if valid {
				t.Fatalf("valid fixture rejected: %v\n%s", err, src)
			}
			return report
		}
	}
	if _, _, _, err := checkSource(report.After); err != nil {
		t.Fatalf("output does not typecheck: %v\n%s", err, report.After)
	}
	if report.TotalErrorsEnhanced > 0 {
		candidate, err := hasRewriteCandidate(src, cfg)
		if err != nil || !candidate {
			t.Fatalf("on-save filter missed a typed rewrite: %v\n%s", err, src)
		}
	}
	// Overwrite can change existing formats on the first pass, but the same
	// configuration must not add its prefix again on subsequent passes.
	again, err := Source(cfg, report.After)
	if !errors.Is(err, ErrNoChanges) || again.After != report.After || again.TotalErrorsEnhanced != 0 {
		t.Fatalf("Source not idempotent: %v\nbefore:\n%s\nafter:\n%s", err, report.After, again.After)
	}
	return report
}
